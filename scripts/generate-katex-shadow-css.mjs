import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const katexCssPath = require.resolve("katex/dist/katex.min.css");
const outputPath = resolve(projectRoot, "src/katex-shadow-css.ts");

const css = await readFile(katexCssPath, "utf8");
const shadowCss = css.replace(/@font-face\{[^{}]*\}/gu, "");
const generated = `// Generated by scripts/generate-katex-shadow-css.mjs.\n// Font faces are bundled in katex-document.css.\nexport const KATEX_SHADOW_CSS = ${JSON.stringify(shadowCss)};\n`;

// BB may lazy-load its native KaTeX CSS only for native math blocks. Plugin
// formulas must also work on a fresh page without any native math. Inline
// WOFF2 fonts because the plugin builder does not emit font URL assets.
let documentCss = css;
for (const match of css.matchAll(/src:url\((fonts\/[^)]+\.woff2)\)[^;}]*/gu)) {
  const font = await readFile(resolve(dirname(katexCssPath), match[1]));
  documentCss = documentCss.replace(
    match[0],
    `src:url(data:font/woff2;base64,${font.toString("base64")}) format("woff2")`,
  );
}
await writeFile(
  resolve(projectRoot, "src/katex-document.css"),
  `/* Generated by scripts/generate-katex-shadow-css.mjs. */\n${documentCss}\n`,
);

await writeFile(outputPath, generated);
console.log(`Generated ${relative(projectRoot, outputPath)} from KaTeX CSS.`);
